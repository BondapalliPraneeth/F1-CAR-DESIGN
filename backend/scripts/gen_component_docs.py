"""Regenerate docs/component_specifications.md from the backend catalogue.

The document is generated (not hand-written) so that it can never drift from the
data the API serves. Run from backend/:

    PYTHONPATH=. python scripts/gen_component_docs.py
"""

from __future__ import annotations

from pathlib import Path

from app.db.repository import component_parameters
from app.domain.components import COMPONENTS, DAMAGE_SCENARIOS

OUT = Path(__file__).resolve().parents[2] / "docs" / "component_specifications.md"
ORDER = ["aerodynamic", "structural", "thermal", "powertrain", "mechanical"]


def esc(s: object) -> str:
    return str(s).replace("|", "\\|")


def main() -> None:
    lines: list[str] = [
        "# Component specifications",
        "",
        "> Generated by `backend/scripts/gen_component_docs.py` from `backend/app/domain/components.py`.",
        "> Do not edit by hand; edit the catalogue and re-run the script.",
        "",
        "The ApexVision AV-1 is an **original, generic open-wheel ground-effect concept car**. It is not a model of any",
        "real team's car. Descriptions are general, publicly documented engineering knowledge about this class of car.",
        "**Every number below is a model assumption** used by the simplified simulation (source `model_assumption`),",
        "not a measured or published value from a real car. All assumptions can be changed in the app's",
        "*Assumptions* tab or per API request.",
        "",
        "## Index",
        "",
        "| # | Component | Category | Analysis panel | Damage susceptibility | Damage types |",
        "|---|---|---|---|---|---|",
    ]
    comps = sorted(COMPONENTS, key=lambda c: (ORDER.index(c.category), COMPONENTS.index(c)))
    for i, c in enumerate(comps, 1):
        lines.append(f"| {i} | [{c.name}](#{c.id.replace('_', '-')}) | {c.category} | {c.analysis_panel} | "
                     f"{c.damage_susceptibility} | {', '.join(d.label for d in c.damage_types)} |")

    for cat in ORDER:
        lines += ["", f"## {cat.capitalize()} components"]
        for c in (c for c in comps if c.category == cat):
            lines += [
                "",
                f'### {c.name} <a id="{c.id.replace("_", "-")}"></a>',
                "",
                f"`id: {c.id}` · category **{c.category}** · panel **{c.analysis_panel}** · "
                f"susceptibility **{c.damage_susceptibility}**",
                "",
                f"- **Position:** {c.position}",
                f"- **Purpose:** {c.purpose}",
                f"- **Primary function:** {c.primary_function}",
                f"- **Construction:** {c.construction}",
                f"- **Performance contribution (model):** {c.performance_contribution}",
                f"- **Susceptibility note:** {c.susceptibility_note}",
                "",
                c.engineering_explanation,
                "",
                "**Typical failure modes**",
                "",
                *[f"- {f}" for f in c.failure_modes],
                "",
                "**Simulated damage types**",
                "",
                "| Type | Model effect | 3D visual representation |",
                "|---|---|---|",
                *[f"| {esc(d.label)} (`{d.id}`) | {esc(d.description)} | {esc(d.visual)} |" for d in c.damage_types],
            ]
            params = component_parameters(c.id)
            if params:
                lines += ["", "**Model parameters (assumptions)**", "", "| Parameter | Value | Unit |", "|---|---|---|"]
                lines += [f"| {esc(p['name'])} | {esc(p['value'])} | {esc(p['unit'])} |" for p in params]
            if c.related:
                lines += ["", "Related: " + ", ".join(f"`{r}`" for r in c.related)]

    lines += ["", "## Preset damage scenarios", "", "| Scenario | Damages |", "|---|---|"]
    for s in DAMAGE_SCENARIOS:
        dmg = ", ".join(f"{d['component_id']}:{d['damage_type']} {d['severity']:g}%" for d in s.get("damages", []))
        lines.append(f"| {esc(s['name'])} | {esc(dmg)} |")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
